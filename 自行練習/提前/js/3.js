// 數字的用法
document.write(6);
document.write(6+3);
document.write(6*3);
document.write(6+3*5);
document.write((6+3)*5);
document.write("<br/>")

var number = 3;
document.write((6+3)*number);
document.write("<br/>");
document.write(9%4);
// 取餘數
document.write("<br/>");

var n = -3;
document.write(Math.abs(n));
// 取絕對值
document.write("<br/>");

document.write(Math.max(2,3,59,26,2556));
document.write("<br/>");
document.write(Math.min(2,3,59,26,2556));
// 在群數字找到最大或最小值
document.write("<br/>");

var s = 12.6;
document.write(Math.round(s));
// 讓數字四捨五入
document.write("<br/>");

document.write(Math.pow(2,3));
// 讓數字次方 (2的3次方)
document.write("<br/>");

document.write(Math.sqrt(36));
// 開根號

document.write(Math.random());
//回傳0-1隨機一個數 *10變0-10
document.write("<br/>");
document.write(Math.round(Math.random()*10));
